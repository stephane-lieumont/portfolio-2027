/** A seeded asset's id, by its key: records name their images through it. */
export function mediaId(key: string): string {
  const asset = MEDIA.find((candidate) => candidate.key === key);
  if (!asset) throw new Error(`no seeded media at ${key}`);
  return asset.id;
}
