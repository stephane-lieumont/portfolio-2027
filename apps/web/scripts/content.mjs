// Writes the projects, 3D pieces, tools and Stack the site is prerendered from into
// src/app/core/data/content/content.generated.ts, which git ignores (ADR-0022).
//
//   node scripts/content.mjs          reads the API at CONTENT_API_URL
//                                     (http://localhost:3000 by default): the build
//   node scripts/content.mjs --seed   reads the API's seed file, no server: the
//                                     tests, the typecheck and `ng serve`
//
// The build never falls back to the seed: an API it cannot read fails it
// (ADR-0008), rather than shipping a site built from something else.
import { readFile, writeFile } from 'node:fs/promises';

const OUTPUT = new URL('../src/app/core/data/content/content.generated.ts', import.meta.url);
const SEED = new URL('../../api/src/db/seed/', import.meta.url);
const RESOLVE = new URL('../../api/src/lib/resolve-content/resolve-content.ts', import.meta.url);

async function fromApi(base) {
  const read = async (path) => {
    const url = `${base.replace(/\/$/, '')}${path}`;
    let response;
    try {
      response = await fetch(url, { signal: AbortSignal.timeout(10_000) });
    } catch (error) {
      throw new Error(
        `cannot reach the content API at ${url} (${error.cause?.code ?? error.message}). ` +
          'Run `pnpm build:site` from the repository root, which seeds and starts one, ' +
          'or point CONTENT_API_URL at a running API.',
      );
    }
    if (!response.ok) throw new Error(`${url} answered ${response.status}`);
    return response.json();
  };
  const content = {
    projects: await read('/api/projects'),
    artworks: await read('/api/artworks'),
    tools: await read('/api/tools'),
    stack: await read('/api/stack'),
  };
  // An unseeded database answers 200 with nothing: a site with no work is a failed build.
  const empty = Object.keys(content).filter((name) => content[name].length === 0);
  if (empty.length > 0) {
    throw new Error(`${base} serves no ${empty.join(', ')}: is its database seeded?`);
  }
  return content;
}

// Resolved and validated as the API does on the way out (references followed,
// trimmed, unknown keys dropped), so the tests see what a build would.
async function fromSeed() {
  const seed = (file) => import(new URL(file, SEED).href);
  const [{ PROJECTS, ARTWORKS }, { MEDIA }, { TOOLS }, { STACK }] = await Promise.all([
    seed('content.ts'),
    seed('media.ts'),
    seed('tools.ts'),
    seed('stack.ts'),
  ]);
  const { resolveContent } = await import(RESOLVE.href);
  return resolveContent({
    media: MEDIA,
    tools: TOOLS,
    stack: STACK,
    projects: PROJECTS,
    artworks: ARTWORKS,
  });
}

function render({ projects, artworks, tools, stack }, source) {
  return [
    `// Generated by scripts/content.mjs from ${source}. Do not edit: the content lives in the API.`,
    "import type { Artwork, Project, StackEntry, Tool } from '@portfolio/shared-types';",
    '',
    `export const PROJECTS: readonly Project[] = ${JSON.stringify(projects, null, 2)};`,
    '',
    `export const ARTWORKS: readonly Artwork[] = ${JSON.stringify(artworks, null, 2)};`,
    '',
    `export const TOOLS: readonly Tool[] = ${JSON.stringify(tools, null, 2)};`,
    '',
    `export const STACK: readonly StackEntry[] = ${JSON.stringify(stack, null, 2)};`,
    '',
  ].join('\n');
}

const fromTheSeed = process.argv.includes('--seed');
// A production build must name its API: never the localhost default (#42).
if (process.env.CONTENT_API_REQUIRED === '1' && !process.env.CONTENT_API_URL) {
  console.error('content: CONTENT_API_URL is required for a production build.');
  process.exit(1);
}
const base = process.env.CONTENT_API_URL ?? 'http://localhost:3000';
const source = fromTheSeed ? 'the API seed' : base;

try {
  const text = render(await (fromTheSeed ? fromSeed() : fromApi(base)), source);
  // Rewriting an unchanged file would restart a running `ng serve` for nothing.
  if ((await readFile(OUTPUT, 'utf8').catch(() => null)) !== text) await writeFile(OUTPUT, text);
  console.log(`content: projects, pieces, tools and Stack from ${source}`);
} catch (error) {
  console.error(`content: ${error.message}`);
  process.exit(1);
}
