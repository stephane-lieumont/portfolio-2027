// The inline script the prerendered pages run, hashed for the site's
// Content-Security-Policy (ADR-0023). Hashes rather than 'unsafe-inline': the
// pages carry the boot scripts of src/index.html, Angular's event replay
// bootstrap, and the critical-CSS loader's `onload` attribute. All of it is
// fixed at build time, so the build can list it, and an injected script that
// is not on the list does not run.
import { createHash } from 'node:crypto';

import { JSDOM, VirtualConsole } from 'jsdom';

// A script element with any other type is data (JSON-LD, Angular's state):
// the browser never runs it, so the policy has nothing to allow.
const EXECUTABLE_TYPES = new Set(['', 'text/javascript', 'application/javascript', 'module']);

function sha256(source) {
  return `'sha256-${createHash('sha256').update(source, 'utf8').digest('base64')}'`;
}

/** The hashes of what a page runs inline: script elements and event-handler attributes. */
export function inlineScriptHashes(html) {
  // A silent console: jsdom's CSS parser complains about modern syntax it does not need here.
  const { document } = new JSDOM(html, { virtualConsole: new VirtualConsole() }).window;
  const scripts = Array.from(document.querySelectorAll('script:not([src])'))
    .filter((script) => EXECUTABLE_TYPES.has((script.getAttribute('type') ?? '').toLowerCase()))
    .map((script) => sha256(script.textContent ?? ''));
  const handlers = Array.from(document.querySelectorAll('*')).flatMap((element) =>
    element
      .getAttributeNames()
      .filter((name) => name.startsWith('on'))
      .map((name) => sha256(element.getAttribute(name) ?? '')),
  );
  return { scripts, handlers };
}

/**
 * The nginx include defining `$csp_inline_scripts`, every page's hashes merged.
 * An attribute handler needs 'unsafe-hashes' besides its hash; it is named
 * only when a page has one, and it lets through those exact handlers only.
 */
export function cspInlineScriptsConf(pages) {
  const scripts = new Set(pages.flatMap((page) => page.scripts));
  const handlers = new Set(pages.flatMap((page) => page.handlers));
  const sources = [...scripts].sort();
  if (handlers.size > 0) sources.push("'unsafe-hashes'", ...[...handlers].sort());
  return [
    '# Generated by apps/web/scripts/write-csp-hashes.mjs from the prerendered pages.',
    'map $host $csp_inline_scripts {',
    `    default "${sources.join(' ')}";`,
    '}',
    '',
  ].join('\n');
}
